package awgmproto

import (
	"crypto/sha256"
	"encoding/hex"
	"io"
	"os"
	"sort"
	"strings"
)

// BinarySHA256 — контрольная сумма исполняемого файла, с которого запущен
// процесс.
//
// Читается по /proc/self/exe, а не по os.Args[0]: после обновления пакета путь
// ведёт на новый файл, а /proc/self/exe — на инод, с которого процесс реально
// запущен. Именно это и надо менеджеру, чтобы заметить усыновлённый процесс со
// старым бинарём.
//
// Зовётся ОДИН раз при старте: SHA256 десятимегабайтного бинаря на mipsel —
// около секунды процессорного времени.
//
// Ошибка возвращается, а не глотается, но обвязка на ней НЕ падает: поле
// binary_sha256 обязательно по §5.2, однако туннель от него не зависит, а
// /proc может оказаться не смонтирован. Договор о поведении при отказе:
// обвязка кладёт причину в last_error и отдаёт ПУСТУЮ строку, а менеджер
// читает пустую строку в обязательном поле как «неизвестно» — не как
// «не совпало». Цена названа честно: у такого процесса подмена бинаря под
// усыновлением останется незамеченной, зато отказ чтения /proc не превращается
// в перезапуск живого туннеля.
func BinarySHA256() (string, error) {
	f, err := os.Open("/proc/self/exe")
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// ConfigHash — отпечаток эффективной конфигурации.
//
// Вход — только аргументы командной строки. Содержимого файлов в отпечатке нет,
// и механизма для него нет намеренно (§5.5 спеки): в отпечаток идёт лишь то,
// что даём процессу мы и что он лишь читает, а у наших ролей таких файлов нет
// ни одного — `-clients-file` freeturn процесс перечитывает сам, `passwords.json`
// сервер сам перезаписывает (`saveDB`). Пустой вход для файлов приглашал бы
// положить туда как раз такой файл и встроить в механизм ложную тревогу, а на
// отпечатке держится решение о перезапуске. Появится файл, который пишем мы, а
// процесс только читает, — механизм завести заново: десяток строк и один тест.
//
// Каноническая форма обязана совпадать побайтово у менеджера и у процесса:
// разные строки дают разный отпечаток навсегда, то есть вечный цикл
// перезапусков, и обнаруживается это после сборки и выкладки бинарей.
//
// Правила: ведущие дефисы срезаются, обе записи значения (`-имя значение` и
// `--имя=значение`) дают одну пару, флаги с префиксом awgm- отбрасываются,
// переключатель без значения даёт "true", повторяющийся флаг — побеждает
// последний, пары сортируются по имени.
//
// Единственное, чего каноническая форма сделать не может: отличить
// `-offset -1` от двух флагов. Типы флагов ей неизвестны, и знать их неоткуда.
// Поэтому значение, начинающееся с дефиса, обязано ехать формой
// `--имя=значение` — требование к сериализации argv у менеджера (плана 3).
func ConfigHash(args []string) string {
	pairs := make(map[string]string)

	for i := 0; i < len(args); i++ {
		name, value, hasValue := splitFlag(args[i])
		if name == "" {
			continue
		}
		if strings.HasPrefix(name, "awgm-") {
			// Флаг обвязки: принадлежит менеджеру, а не конфигурации.
			if !hasValue && i+1 < len(args) && !strings.HasPrefix(args[i+1], "-") {
				i++
			}
			continue
		}
		if !hasValue {
			value = "true"
			if i+1 < len(args) && !strings.HasPrefix(args[i+1], "-") {
				value = args[i+1]
				i++
			}
		}
		pairs[name] = value // побеждает последний
	}

	names := make([]string, 0, len(pairs))
	for n := range pairs {
		names = append(names, n)
	}
	sort.Strings(names)

	h := sha256.New()
	for _, n := range names {
		h.Write([]byte(n))
		h.Write([]byte{0})
		h.Write([]byte(pairs[n]))
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))
}

// splitFlag разбирает одну запись argv в имя и значение, понимая
// "--имя=значение", "--имя", "-имя", а также запись вовсе без дефисов
// ("имя", "имя=значение") — §5.5 п.2 требует, чтобы `-no-nat`, `--no-nat` и
// `no-nat` давали одно имя.
//
// Требование к вызывающим: разборщик в пакете обязан остаться ОДИН. Тому, кто
// разбирает настоящий argv (probe.go задачи 4), звать его следует через
// обёртку, требующую ведущий дефис, — иначе позиционный токен притворится
// флагом: имя здесь принимается и вовсе без дефисов, этого требует §5.5 п.2.
// Две копии разбора — прямая дорога к двум каноническим формам и вечному циклу
// перезапусков.
func splitFlag(arg string) (name, value string, hasValue bool) {
	body := strings.TrimLeft(arg, "-")
	if body == "" {
		return "", "", false
	}
	if n, v, ok := strings.Cut(body, "="); ok {
		return n, v, true
	}
	return body, "", false
}
