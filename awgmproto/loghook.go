package awgmproto

import (
	"os"
	"sync"
	"time"
)

// LogCapBytes — потолок размера журнала. Файл живёт в оперативной памяти
// (tmpfs), а запуск во времени не ограничен: без потолка месяц аптайма
// четырёх процессов съел бы десятки мегабайт на роутере со 128 МБ.
const LogCapBytes = 1 << 20

// CapPeriod — как часто сторож Log.WatchCap спрашивает у ядра размер журнала и
// усекает его при переборе LogCapBytes. Это НЕ период записи и не срок жизни
// строк: между двумя проверками журнал свободно перерастает потолок, и потерян
// при усечении будет весь накопленный текст, а не старая его часть.
//
// Значение — компромисс между этим перебором и стоимостью проверки. Тридцать
// секунд: самый говорливый из четырёх процессов не успевает за них написать
// заметную долю мегабайта, а сам stat(2) раз в полминуты на роутере не стоит
// ничего. Живёт здесь, а не в обвязках: потолок у четырёх бинарей общий, и
// период проверки обязан ходить с ним в паре, а не тремя копиями, способными
// разъехаться порознь.
const CapPeriod = 30 * time.Second

// Log — журнал процесса.
//
// Открывается с усечением: содержимое файла всегда равно журналу ТЕКУЩЕГО
// запуска. Усечение делает процесс, а не менеджер — иначе оно гонялось бы с
// записью ещё живого прежнего процесса. O_APPEND делает записи атомарными
// относительно друг друга, в том числе для порождённых хелперов, которым
// дескриптор наследуется.
type Log struct {
	mu   sync.Mutex
	f    *os.File
	size int64
}

func OpenLog(path string) (*Log, error) {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC|os.O_APPEND, 0o600)
	if err != nil {
		return nil, err
	}
	return &Log{f: f}, nil
}

// Write пишет строку, усекая файл при достижении потолка. Потеря старых строк
// безвредна: все предикаты здоровья работают по хвосту.
func (l *Log) Write(p []byte) (int, error) {
	l.mu.Lock()
	defer l.mu.Unlock()

	if l.size+int64(len(p)) > LogCapBytes {
		if err := l.f.Truncate(0); err != nil {
			return 0, err
		}
		l.size = 0
	}
	n, err := l.f.Write(p)
	l.size += int64(n)
	return n, err
}

// Fd — дескриптор для наследования хелперами: их вывод обязан попадать в тот
// же журнал, иначе маркеры, которые читают предикаты, исчезнут вместе с ним.
func (l *Log) Fd() uintptr { return l.f.Fd() }

func (l *Log) Close() error { return l.f.Close() }
