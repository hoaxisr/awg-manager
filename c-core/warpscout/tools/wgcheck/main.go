	pt := "Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
	a, _ := chacha20poly1305.New(akey)
	ct := a.Seal(nil, anonce, []byte(pt), aad)
	p("VEC_AEAD_KEY", hx(akey))
	p("VEC_AEAD_NONCE", hx(anonce))
	p("VEC_AEAD_AD", hx(aad))
	p("VEC_AEAD_PT", pt)
	p("VEC_AEAD_CT", hx(ct[:len(pt)]))
