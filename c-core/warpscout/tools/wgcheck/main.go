// ---------------------------------------------------------------- responder

type session struct {
	localIdx, remoteIdx uint32
	send, recv          []byte
	sendCtr             uint64
	addr                *net.UDPAddr
	ipID                uint16
	tcpSeq              map[uint16]uint32
}

var (
	mu       sync.Mutex
	sessions = map[uint32]*session{}
	reorder  bool
	reserved = []byte{0xaa, 0xbb, 0xcc}
)

func responder(listen, privB64, traceBody string) {
	priv, err := base64.StdEncoding.DecodeString(privB64)
	if err != nil || len(priv) != 32 {
		log.Fatalf("bad -priv")
	}
	pub := dh(priv, curve25519.Basepoint)
	log.Printf("responder public key: %s", base64.StdEncoding.EncodeToString(pub))
	ua, _ := net.ResolveUDPAddr("udp", listen)
	conn, err := net.ListenUDP("udp", ua)
	if err != nil {
		log.Fatal(err)
	}
	fmt.Println("READY")
	os.Stdout.Sync()
	psk := make([]byte, 32)
	mac1Key := h256([]byte(labelMac1), pub)
	b := make([]byte, 2048)
	for {
		n, from, err := conn.ReadFromUDP(b)
		if err != nil {
			log.Fatal(err)
		}
		pkt := append([]byte{}, b[:n]...)
		if n < 4 {
			continue
		}
		gotRes := hx(pkt[1:4])
		pkt[1], pkt[2], pkt[3] = 0, 0, 0
		switch {
		case pkt[0] == 1 && n == 148:
			if !hmac.Equal(mac128(mac1Key, pkt[:116]), pkt[116:132]) {
				log.Printf("INIT from %v: mac1 MISMATCH", from)
				continue
			}
			C := h256([]byte(construction))
			H := h256(C, []byte(identifier))
			H = h256(H, pub)
			eI := pkt[8:40]
			C = kdf(C, eI, 1)[0]
			H = h256(H, eI)
			k := kdf(C, dh(priv, eI), 2)
			C = k[0]
			sI, err := open(k[1], 0, pkt[40:88], H)
			if err != nil {
				log.Printf("INIT static decrypt FAIL")
				continue
			}
			H = h256(H, pkt[40:88])
			k = kdf(C, dh(priv, sI), 2)
			C = k[0]
			ts, err := open(k[1], 0, pkt[88:116], H)
			if err != nil {
				log.Printf("INIT timestamp decrypt FAIL")
				continue
			}
			H = h256(H, pkt[88:116])
			log.Printf("INIT ok from %v reserved=%s initiator=%s tai64n=%s", from, gotRes,
				base64.StdEncoding.EncodeToString(sI), hx(ts))
			// response
			eRpriv := make([]byte, 32)
			rand.Read(eRpriv)
			eR := dh(eRpriv, curve25519.Basepoint)
			resp := make([]byte, 92)
			resp[0] = 2
			var li [4]byte
			rand.Read(li[:])
			localIdx := binary.LittleEndian.Uint32(li[:])
			binary.LittleEndian.PutUint32(resp[4:], localIdx)
			copy(resp[8:12], pkt[4:8])
			copy(resp[12:44], eR)
			C = kdf(C, eR, 1)[0]
			H = h256(H, eR)
			C = kdf(C, dh(eRpriv, eI), 1)[0]
			C = kdf(C, dh(eRpriv, sI), 1)[0]
			k = kdf(C, psk, 3)
			C = k[0]
			H = h256(H, k[1])
			empty := seal(k[2], 0, nil, H)
			copy(resp[44:60], empty)
			copy(resp[60:76], mac128(h256([]byte(labelMac1), sI), resp[:60]))
			tk := kdf(C, nil, 2)
			s := &session{localIdx: localIdx, remoteIdx: binary.LittleEndian.Uint32(pkt[4:8]),
				send: tk[1], recv: tk[0], addr: from, tcpSeq: map[uint16]uint32{}}
			mu.Lock()
			sessions[localIdx] = s
			mu.Unlock()
			copy(resp[1:4], reserved)
			conn.WriteToUDP(resp, from)
		case pkt[0] == 4 && n >= 32:
			idx := binary.LittleEndian.Uint32(pkt[4:8])
			mu.Lock()
			s := sessions[idx]
			mu.Unlock()
			if s == nil {
				log.Printf("DATA unknown receiver %08x", idx)
				continue
			}
			ctr := binary.LittleEndian.Uint64(pkt[8:16])
			pt, err := open(s.recv, ctr, pkt[16:], nil)
			if err != nil {
				log.Printf("DATA decrypt FAIL ctr=%d", ctr)
				continue
			}
			s.addr = from
			handleInner(conn, s, pt, traceBody)
		default:
			log.Printf("unexpected packet type=%d len=%d", pkt[0], n)
		}
	}
}

func csum(b []byte, init uint32) uint16 {
	s := init
	for i := 0; i+1 < len(b); i += 2 {
		s += uint32(b[i])<<8 | uint32(b[i+1])
	}
	if len(b)%2 == 1 {
		s += uint32(b[len(b)-1]) << 8
	}
	for s>>16 != 0 {
		s = (s & 0xffff) + (s >> 16)
	}
	return ^uint16(s)
}

func sendInner(conn *net.UDPConn, s *session, ip []byte) {
	pad := (16 - len(ip)%16) % 16
	pt := append(append([]byte{}, ip...), make([]byte, pad)...)
	out := make([]byte, 16)
	out[0] = 4
	copy(out[1:4], reserved)
	binary.LittleEndian.PutUint32(out[4:], s.remoteIdx)
	binary.LittleEndian.PutUint64(out[8:], s.sendCtr)
	out = append(out, seal(s.send, s.sendCtr, pt, nil)...)
	s.sendCtr++
	conn.WriteToUDP(out, s.addr)
}

func ipv4(s *session, proto byte, src, dst, payload []byte) []byte {
	ip := make([]byte, 20+len(payload))
	ip[0] = 0x45
	binary.BigEndian.PutUint16(ip[2:], uint16(len(ip)))
	s.ipID++
	binary.BigEndian.PutUint16(ip[4:], s.ipID)
	ip[8] = 64
	ip[9] = proto
	copy(ip[12:16], src)
	copy(ip[16:20], dst)
	binary.BigEndian.PutUint16(ip[10:], csum(ip[:20], 0))
	copy(ip[20:], payload)
	return ip
}

func tcpSeg(src, dst []byte, sport, dport uint16, seq, ack uint32, flags byte, data []byte) []byte {
	t := make([]byte, 20+len(data))
	binary.BigEndian.PutUint16(t[0:], sport)
	binary.BigEndian.PutUint16(t[2:], dport)
	binary.BigEndian.PutUint32(t[4:], seq)
	binary.BigEndian.PutUint32(t[8:], ack)
	t[12] = 5 << 4
	t[13] = flags
	binary.BigEndian.PutUint16(t[14:], 65535)
	copy(t[20:], data)
	ph := make([]byte, 12)
	copy(ph[0:4], src)
	copy(ph[4:8], dst)
	ph[9] = 6
	binary.BigEndian.PutUint16(ph[10:], uint16(len(t)))
	binary.BigEndian.PutUint16(t[16:], csum(append(ph, t...), 0))
	return t
}

func handleInner(conn *net.UDPConn, s *session, p []byte, traceBody string) {
	if len(p) == 0 {
		log.Printf("keepalive")
		return
	}
	if len(p) < 20 || p[0]>>4 != 4 {
		log.Printf("non-ipv4 inner")
		return
	}
	ihl := int(p[0]&15) * 4
	tot := int(binary.BigEndian.Uint16(p[2:]))
	if tot > len(p) || csum(p[:ihl], 0) != 0 {
		log.Printf("BAD IP header/checksum")
		return
	}
	p = p[:tot]
	src, dst := p[12:16], p[16:20]
	pl := p[ihl:]
	switch p[9] {
	case 1:
		if csum(pl, 0) != 0 {
			log.Printf("BAD ICMP checksum")
			return
		}
		if pl[0] == 8 {
			log.Printf("ICMP echo %v -> %v id=%d seq=%d", net.IP(src), net.IP(dst),
				binary.BigEndian.Uint16(pl[4:]), binary.BigEndian.Uint16(pl[6:]))
			r := append([]byte{}, pl...)
			r[0] = 0
			r[2], r[3] = 0, 0
			binary.BigEndian.PutUint16(r[2:], csum(r, 0))
			sendInner(conn, s, ipv4(s, 1, dst, src, r))
		}
	case 6:
		ph := make([]byte, 12)
		copy(ph[0:4], src)
		copy(ph[4:8], dst)
		ph[9] = 6
		binary.BigEndian.PutUint16(ph[10:], uint16(len(pl)))
		if csum(append(ph, pl...), 0) != 0 {
			log.Printf("BAD TCP checksum")
			return
		}
		sport := binary.BigEndian.Uint16(pl[0:])
		dport := binary.BigEndian.Uint16(pl[2:])
		seq := binary.BigEndian.Uint32(pl[4:])
		off := int(pl[12]>>4) * 4
		flags := pl[13]
		data := pl[off:]
		switch {
		case flags&0x04 != 0:
			log.Printf("TCP RST from %d -> %v:%d", sport, net.IP(dst), dport)
		case flags&0x02 != 0:
			mss := 0
			if off > 20 && pl[20] == 2 {
				mss = int(binary.BigEndian.Uint16(pl[22:]))
			}
			log.Printf("TCP SYN %v:%d -> %v:%d mss=%d", net.IP(src), sport, net.IP(dst), dport, mss)
			iss := uint32(1000000)
			s.tcpSeq[sport] = iss + 1
			sendInner(conn, s, ipv4(s, 6, dst, src, tcpSeg(dst, src, dport, sport, iss, seq+1, 0x12, nil)))
		case len(data) > 0:
			log.Printf("TCP DATA %d bytes: %q", len(data), strings.SplitN(string(data), "\r\n", 2)[0])
			my := s.tcpSeq[sport]
			ack := seq + uint32(len(data))
			body := traceBody
			resp := fmt.Sprintf("HTTP/1.1 200 OK\r\nContent-Type: text/plain\r\nContent-Length: %d\r\nConnection: close\r\n\r\n%s", len(body), body)
			cut := len(resp) / 2
			s1 := tcpSeg(dst, src, dport, sport, my, ack, 0x18, []byte(resp[:cut]))
			s2 := tcpSeg(dst, src, dport, sport, my+uint32(cut), ack, 0x19, []byte(resp[cut:]))
			if reorder {
				sendInner(conn, s, ipv4(s, 6, dst, src, s2))
				time.Sleep(5 * time.Millisecond)
				sendInner(conn, s, ipv4(s, 6, dst, src, s1))
			} else {
				sendInner(conn, s, ipv4(s, 6, dst, src, s1))
				sendInner(conn, s, ipv4(s, 6, dst, src, s2))
			}
		default:
			// pure ACK
		}
	default:
		log.Printf("inner proto %d", p[9])
	}
}

func main() {
	log.SetFlags(log.Ltime | log.Lmicroseconds)
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: wgcheck vectors | responder [-listen addr] -priv b64 | keygen")
		os.Exit(2)
	}
	switch os.Args[1] {
	case "vectors":
		vectors()
	case "keygen":
		priv := make([]byte, 32)
		rand.Read(priv)
		pub := dh(priv, curve25519.Basepoint)
		fmt.Printf("%s %s\n", base64.StdEncoding.EncodeToString(priv), base64.StdEncoding.EncodeToString(pub))
	case "responder":
		fs := flag.NewFlagSet("responder", flag.ExitOnError)
		listen := fs.String("listen", "127.0.0.1:51999", "udp listen address")
		priv := fs.String("priv", "", "responder static private key (base64)")
		trace := fs.String("trace", "fl=1f1\nh=cp.cloudflare.com\nip=203.0.113.9\nts=1.0\nvisit_scheme=http\nuag=awgm-warpscout\ncolo=HEL\nsliver=none\nhttp=http/1.1\nloc=FI\ntls=off\nsni=off\nwarp=on\ngateway=off\nrbi=off\nkex=none\n", "trace body")
		fs.BoolVar(&reorder, "reorder", false, "send HTTP response segments out of order")
		fs.Parse(os.Args[2:])
		responder(*listen, *priv, *trace)
	default:
		os.Exit(2)
	}
}
