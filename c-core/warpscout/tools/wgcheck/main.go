	p("VEC_X_A_PRIV", hx(apriv))
	p("VEC_X_B_PRIV", hx(bpriv))
	p("VEC_X_A_PUB", hx(apub))
	p("VEC_X_B_PUB", hx(bpub))
	p("VEC_X_SHARED", hx(dh(apriv, bpub)))
	fmt.Println("#endif")
