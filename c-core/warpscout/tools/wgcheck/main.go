	buf := make([]byte, 64)
	for i := range key {
		key[i] = byte(i)
	}
	for i := range buf {
		buf[i] = byte(i)
	}
	big := make([]byte, 1000)
	for i := range big {
		big[i] = byte(i * 7)
	}
	kh := func(k []byte, in []byte) []byte { h, _ := blake2s.New256(k); h.Write(in); return h.Sum(nil) }

	p := func(name, v string) { fmt.Printf("#define %s \\\n    \"%s\"\n", name, v) }
	fmt.Println("/* Generated by tools/wgcheck (go run . vectors) from golang.org/x/crypto.")
	fmt.Println(" * RFC 7693 / RFC 8439 / RFC 7748 inputs. Do not edit by hand. */")
	fmt.Println("#ifndef WS_SELFTEST_VECTORS_H\n#define WS_SELFTEST_VECTORS_H")
	p("VEC_B2S_ABC", hx(h256([]byte("abc"))))
	p("VEC_B2S_KEYED_0", hx(kh(key, nil)))
	p("VEC_B2S_KEYED_64", hx(kh(key, buf)))
	p("VEC_B2S_1000", hx(h256(big)))
	p("VEC_B2S128_KEYED", hx(mac128(key, big[:116])))
	p("VEC_HMAC", hx(hmacB2s(key, []byte("wireguard"))))
	t := kdf(key, buf[:32], 3)
	p("VEC_KDF_T1", hx(t[0]))
	p("VEC_KDF_T2", hx(t[1]))
	p("VEC_KDF_T3", hx(t[2]))

	akey, _ := hex.DecodeString("808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9f")
	anonce, _ := hex.DecodeString("070000004041424344454647")
