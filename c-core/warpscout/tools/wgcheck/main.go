// wgcheck: independent Go (x/crypto) reference for awgm-warpscout.
//
//	go run . vectors      > ../../src/selftest_vectors.h
//	go run . responder -listen 127.0.0.1:51999 -priv <b64>
//
// The responder implements the WireGuard responder side of
// Noise_IKpsk2_25519_ChaChaPoly_BLAKE2s using golang.org/x/crypto only, then
// answers in-tunnel ICMP echo and a tiny TCP/HTTP "/cdn-cgi/trace" server, so
// the C initiator can be validated end-to-end on localhost.
