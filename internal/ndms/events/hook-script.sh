#!/bin/sh
# 50-awg-manager.sh — NDMS hook forwarder for awg-manager (F571).
# Одна запись в spool и выход: ни fork'ов, ни сети. Порядок строк в файле =
# порядок исполнения хуков NDMS (очередь последовательная); демон читает
# файл через inotify. Каталог spool создаёт читатель на старте и сносит на
# остановке; >> каталог не создаёт, так что остановленный демон строк не
# копит, а пропущенное покрывает полный список на старте. Признак — каталог,
# а не файл: при ротации файл на миг отсутствует (rename, затем создание).
# 2>/dev/null стоит ДО >>: иначе отказ открыть файл печатается в stderr.
d=${0%/*}; d=${d%.d}
echo "type=${d##*/}&id=${id}&system_name=${system_name}&layer=${layer}&level=${level}&address=${address}" \
    2>/dev/null >> /var/run/awg-manager/hooks/ndm-hooks
exit 0
