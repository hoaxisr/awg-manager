package proxyrt

import (
	"context"
	"errors"
	"strings"
)

// OwnedResource — ресурс роутера, помеченный нашей меткой владения.
//
// Label — ФАКТИЧЕСКОЕ описание ресурса, как оно прочитано с роутера, а не
// константа из списка меток. Требование к нему одно: описание нашего ресурса
// НАЧИНАЕТСЯ с одной из запрошенных меток (см. Scanner). Подставлять сюда
// константу сканеру незачем и нечем — у клиентского OpkgTun описание состоит
// из метки и имени инстанса, и второго поля под имя в NDMS нет.
type OwnedResource struct {
	Label string
	Name  string
}

// Scanner перечисляет ресурсы роутера с нашими метками. Меток несколько:
// у клиента и сервера они разные.
//
// Совпадение — по ПРЕФИКСУ описания, и того же ждёт от Label сам уборщик: он
// перепроверяет метку своим же списком (Sweep) и потому не требует от сканера
// ничего, кроме честно прочитанного описания. Равенство здесь означало бы
// негласное требование «подставь вместо прочитанного константу», нарушение
// которого молча выключает поиск сирот — так клиентские сироты не находились
// НИКОГДА в старом реапе.
type Scanner interface {
	Scan(ctx context.Context, labels []string) ([]OwnedResource, error)
}

// Remover сносит ресурс.
type Remover interface {
	Remove(ctx context.Context, r OwnedResource) error
}

// Sweeper удаляет то, что помечено нашей меткой, но не объявлено ни одним
// живым инстансом. Это единственный путь удаления ресурсов: воркеры инстансов
// ничего не сносят.
type Sweeper struct {
	sc     Scanner
	rm     Remover
	labels []string
}

// NewSweeper паникует на пустом списке меток: уборщик — единственный путь
// удаления, и без меток он молча не удалял бы ничего никогда, накапливая сирот.
// Это ошибка программирования, а не режим работы. По той же причине паникует
// на nil-сканере и nil-сносчике: без них уборка упала бы посреди работы, а не
// при сборке движка.
func NewSweeper(sc Scanner, rm Remover, labels []string) *Sweeper {
	if sc == nil || rm == nil {
		panic("proxyrt: NewSweeper без сканера или сносчика")
	}
	if len(labels) == 0 {
		panic("proxyrt: NewSweeper без меток владения — уборщик не удалял бы ничего")
	}
	return &Sweeper{sc: sc, rm: rm, labels: labels}
}

// ours — наша ли метка. Сверка по префиксу: описание нашего ресурса
// начинается с метки, а хвост у клиента занят именем инстанса
// (roles.ClientDescription). Метка, не совпавшая ни с одной нашей, — не наша:
// ресурс не рассматривается вовсе, потому что цена ошибки здесь — снесённый
// чужой интерфейс роутера.
func (s *Sweeper) ours(label string) bool {
	for _, l := range s.labels {
		if strings.HasPrefix(label, l) {
			return true
		}
	}
	return false
}

// Sweep сносит то, что помечено нашей меткой, но не объявлено ведомостью.
//
// declare собирает ведомость объявленных имён и получает ИМЕНА, которые нашёл
// скан. Порядок «скан → ведомость → снос» из-за этого невыразим неправильно:
// собрать ведомость раньше скана нечем — аргумента ещё не существует, — а
// подсунуть вместо найденного своё нельзя, срез за пределы вызова не выходит.
//
// Так и должно быть, потому что порядок здесь несущий: между сканом и
// ведомостью инстанс может появиться, и ведомость, взятая раньше, о нём не
// знает — его свежий интерфейс был бы снесён вместе с permit'ами его политик,
// а permit пересозданием интерфейса не воскресает.
//
// Скан упал — не сносим ничего: «не знаем» не равно «наш и лишний». Отказ
// declare — то же самое и по той же причине.
//
// Метка перепроверяется своим же списком (по префиксу, как и у сканера):
// довод «сканер вернул только наше» верен ровно до бага в сканере, а цена
// бага здесь — снесённый чужой интерфейс роутера.
//
// Аллокатора уборка не спрашивает. Прежде решение принималось под его локом и
// пропускало ресурс, чей номер закреплён: без этого свежесозданный интерфейс
// сносился бы, пока инстанс не успел объявиться. Ту же гонку закрывает
// порядок, и закрывает полнее: запись ложится РАНЬШЕ интерфейса на всех трёх
// путях (Create, Boot, update), значит инстанс, чей интерфейс попал в скан, к
// моменту сбора ведомости уже имеет запись. Номер, закреплённый без записи и
// без интерфейса, уборке не интересен — сносить по нему нечего.
//
// Отмена контекста прекращает сносы и отказом уборки не считается — так же,
// как отмена отделена от отказа в цикле реконсиляции и воркере.
func (s *Sweeper) Sweep(ctx context.Context,
	declare func(found []string) (map[string]bool, error)) ([]string, error) {
	scanned, err := s.sc.Scan(ctx, s.labels)
	if err != nil {
		return nil, err
	}
	ours := make([]OwnedResource, 0, len(scanned))
	names := make([]string, 0, len(scanned))
	for _, r := range scanned {
		if s.ours(r.Label) {
			ours = append(ours, r)
			names = append(names, r.Name)
		}
	}

	declared, err := declare(names)
	if err != nil {
		return nil, err
	}

	var removed []string
	var firstErr error
	for _, r := range ours {
		if declared[r.Name] {
			continue
		}
		if ctx.Err() != nil {
			break
		}
		if rmErr := s.rm.Remove(ctx, r); rmErr != nil {
			// Отмена — не отказ уборки, откуда бы она ни пришла: и из состояния
			// контекста, и возвратом из самого Remove.
			if ctx.Err() != nil || errors.Is(rmErr, context.Canceled) {
				break
			}
			if firstErr == nil {
				firstErr = rmErr
			}
			continue
		}
		removed = append(removed, r.Name)
	}
	return removed, firstErr
}
