package proxyrt

import (
	"context"
	"time"
)

// Resource — единица владения и сверки. Знает только про себя: соседей не
// видит, порядок применения задаётся списком роли.
type Resource interface {
	ID() ResourceID
	// Observe возвращает фактическое состояние. Ошибка либо Known=false
	// означают «не смогли посмотреть» и дают StatusUnknown, а не «ресурса нет».
	Observe(ctx context.Context) (Observation, error)
	// Plan — чистая функция: по наблюдению возвращает шаги, ничего не делая.
	// Класть в Step.Args ту же карту, что пришла в Observation.Attrs, нельзя:
	// план — неизменяемые данные, общая ссылка сделала бы его изменяемым.
	Plan(obs Observation) []Step
	// Apply — единственное место с побочными эффектами.
	Apply(ctx context.Context, s Step) error
	// RecheckAfter — период подстраховочной сверки. 0 = только по событиям.
	RecheckAfter() time.Duration
}

// Role — декларация состава инстанса. Порядок ресурсов значим: список работает
// как цепочка, ресурс после неисправного получает StatusBlocked.
//
// Намерение — параметр, а не внешняя раскраска: при disabled роль объявляет
// «интерфейс без адреса и down», а не тот же состав, что при enabled. Иначе
// намерение пришлось бы дублировать внутрь конфига.
//
// Желаемое зависит и от наблюдений: адрес raw-клиента выдаёт сервер, поэтому
// он не может быть намерением.
//
// Состав ресурсов обязан быть СТАБИЛЕН для данной пары (intent, cfg): от
// наблюдений зависят желаемые ЗНАЧЕНИЯ, но не членство в списке. Ресурс,
// появляющийся в декларации только после наблюдения соседа, не будет наблюдён
// ни в одном проходе (первый вызов идёт с пустыми наблюдениями), не даст шагов,
// и инстанс молча зависнет в waiting: план пуст, потолок не срабатывает. Все
// роли обязаны объявлять ресурс всегда, а неизвестность его желаемого значения
// выражать через наблюдение.
type Role interface {
	Resources(intent Intent, cfg any, obs Observations) []Resource
}

// BackoffResetter — способность роли снять у своего процесса паузу повторного
// старта («анти-флаппинг», до пяти минут). Отдельным интерфейсом, а не методом
// Role: Role — декларация состава, чистая и без побочных эффектов, а это
// мутация состояния ресурса.
//
// Зовёт её единственная точка правки записи инстанса (manager.Update): правка
// конфига руками могла устранить причину отказа, и держать клиента в паузе
// значило бы держать его ровно в тот момент, когда человек его чинит.
//
// Реализуют её ВСЕ роли с процессом, то есть все четыре. Новая роль с
// процессом обязана реализовать тоже: инстанс зовёт способность по
// приведению типа, и забывшая роль потеряет сброс молча.
type BackoffResetter interface{ ResetStartBackoff() }

// Observations — снимок наблюдений одного прохода. Обёртка над картой:
// методы с value-приёмником, карта общая, копия структуры видит те же данные.
type Observations struct {
	m map[ResourceID]observed
}

type observed struct {
	seen   bool
	obs    Observation
	err    error
	failed string
}

func NewObservations() Observations {
	return Observations{m: make(map[ResourceID]observed)}
}

// Put кладёт результат наблюдения. Ошибка сохраняется целиком: причина
// недоступности обязана доехать до состояния ресурса.
func (o Observations) Put(id ResourceID, obs Observation, err error) {
	rec := o.m[id]
	rec.seen = true
	rec.obs, rec.err = obs, err
	o.m[id] = rec
}

// MarkFailed помечает ресурс отказавшим при применении. Отказ прерывает весь
// прогон, поэтому метка живёт до его конца; ещё один шанс шаг получает только в
// следующем прогоне, который наблюдает заново.
func (o Observations) MarkFailed(id ResourceID, reason string) {
	rec := o.m[id]
	rec.failed = reason
	o.m[id] = rec
}

// Get отдаёт наблюдение ресурса. Нужен ролям: желаемое значение одного ресурса
// вычисляется из наблюдения другого — адрес интерфейса из состояния процесса.
//
// ok=false означает «опираться нельзя» и покрывает все причины разом: ресурс не
// наблюдался в этом проходе, наблюдатель вернул ошибку, наблюдатель вернул «не
// смотрел», применение к ресурсу уже отказало. Одним ответом, а не набором
// полей: у Plan все четыре дают один и тот же вывод, и роль обязана прочитать
// их так же — иначе слепое наблюдение станет основанием для решения.
func (o Observations) Get(id ResourceID) (Observation, bool) {
	rec := o.m[id]
	return rec.obs, rec.seen && rec.err == nil && rec.failed == "" && rec.obs.Known
}
