package proxyrt

import (
	"errors"
	"sync"
)

// ErrNoFreeIndex — в диапазоне не осталось свободных номеров.
var ErrNoFreeIndex = errors.New("нет свободного индекса в диапазоне")

// IndexRange — диапазон номеров интерфейсов. Для wdtt это OpkgTun17..49:
// 0..9 занят fakeip, 10..16 — awg.
type IndexRange struct {
	Min int
	Max int
}

// Allocator раздаёт номера из пространства, общего для всех инстансов обеих
// подсистем. «Один воркер на инстанс» сериализует только внутри инстанса,
// поэтому выделение обязано идти под собственным локом — иначе два воркера
// одновременно увидят один и тот же свободный номер.
//
// Тем же локом пользуется уборщик: ресурс без живой декларации не принадлежит
// ни одному воркеру.
type Allocator struct {
	mu   sync.Mutex
	rng  IndexRange
	held map[int]string // номер → идентификатор владельца
}

func NewAllocator(r IndexRange) *Allocator {
	return &Allocator{rng: r, held: make(map[int]string)}
}

// AllocIndex выдаёт номер инстансу owner. pinned — ранее закреплённый за
// инстансом номер: его стоит вернуть, пока он свободен, потому что пользователь
// мог сослаться на имя интерфейса в permit'ах политики.
//
// taken — номера, занятые СНАРУЖИ аллокатора: живые интерфейсы и персисты
// ДРУГИХ владельцев. Собственные ресурсы owner в taken попадать не должны.
// Иначе закрепление сработает наоборот: свой же живой интерфейс будет прочитан
// как чужой, и владелец молча получит другой номер — то есть имя OpkgTunN
// сменится, а permit'ы пользователя в политиках повиснут. После рестарта
// демона held пуст, и это единственная защита.
//
// Идемпотентна: повторный вызов с тем же owner и pinned возвращает тот же
// номер, потому что собственный захват не считается занятым. Без этого
// закрепление работало бы наоборот — второй проход реконсиляции сменил бы имя
// интерфейса и порвал permit'ы пользователя.
func (a *Allocator) AllocIndex(owner string, pinned int, taken map[int]bool) (int, error) {
	a.mu.Lock()
	defer a.mu.Unlock()

	free := func(i int) bool {
		h, ok := a.held[i]
		return (!ok || h == owner) && !taken[i]
	}

	if pinned >= a.rng.Min && pinned <= a.rng.Max && free(pinned) {
		a.held[pinned] = owner
		return pinned, nil
	}
	for i := a.rng.Min; i <= a.rng.Max; i++ {
		if free(i) {
			a.held[i] = owner
			return i, nil
		}
	}
	return 0, ErrNoFreeIndex
}

// Release освобождает все номера владельца. Зовётся только при удалении
// инстанса: выключенный инстанс держит номер, чтобы permit'ы пользователя не
// повисли на чужом имени.
//
// Освобождение именно по владельцу, а не по номеру: иначе остался бы способ
// освободить чужой номер.
func (a *Allocator) Release(owner string) {
	a.mu.Lock()
	for idx, h := range a.held {
		if h == owner {
			delete(a.held, idx)
		}
	}
	a.mu.Unlock()
}

// WithLock выполняет f под тем же локом, что и выделение номеров, и передаёт в
// неё предикат isHeld. Нужен уборщику: решение «этот ресурс лишний» и выделение
// номера не должны идти одновременно, а само решение обязано консультировать
// состояние аллокатора — иначе лок не защищает ничего.
//
// Предикат отдаётся именно аргументом, а не отдельным экспортированным методом:
// так возможность прочитать held существует только внутри критической секции, и
// прочитать её мимо лока (гонка, видимая лишь под -race) технически нельзя.
//
// Лок не реентрантен: вызов AllocIndex или Release внутри f — дедлок.
func (a *Allocator) WithLock(f func(isHeld func(idx int) bool)) {
	a.mu.Lock()
	defer a.mu.Unlock()
	f(a.isHeldLocked)
}

// isHeldLocked сообщает, закреплён ли номер за каким-либо владельцем. Лок не
// берёт: зовётся только из-под WithLock.
func (a *Allocator) isHeldLocked(idx int) bool { _, ok := a.held[idx]; return ok }
