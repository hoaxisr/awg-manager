package opkgtun

import "runtime"

// Пул номеров OpkgTun — КАНОНИЧЕСКАЯ карта. Остальные владельцы ссылаются
// сюда; копий карты быть не должно (#891 родился ровно из их расхождения).
//
//	0..1        — достаются ТОЛЬКО режимам роутера (fakeip / policy-tun):
//	              отступать им некуда, а kernel и прокси имеют запас доверху
//	2..потолок  — общий пул; порядок обхода задаёт Pool.order:
//	              режимы роутера идут 0..потолок, все остальные 10..потолок,
//	              затем вниз от min(9, потолок) до 2
//
// Карта живёт ЗДЕСЬ, рядом с единственным, кто по ней раздаёт. Прежде она
// лежала в internal/tunnel, и пул импортировал чужой пакет ради собственных
// границ; пока у номеров было четыре раздающих, это было неважно, а с одним
// стало прямо наоборот.
//
// Собственных окон у владельцев больше нет: с #891 их выдал бы разошедшимися
// первый же потолок прошивки. Пул пересекается между владельцами на ВСЕХ
// архитектурах, поэтому занятость считается по всем пяти поставщикам сразу
// (cmd/awg-manager.opkgTunOwners), а не по своему поддиапазону.
//
// NativeWG в нумерации не участвует: OpkgTun он не создаёт (живёт как
// Wireguard<N>). Его идентификаторы занимают пространство КЛЮЧЕЙ хранилища, и
// это пространство РАЗВЕДЕНО с номерами OpkgTun: пол NativeWG начинается выше
// потолка этой архитектуры (storage.nwgFloor, F317), иначе за один ключ спорили
// бы двое — пул, держащий резервацию, и перебор, видящий только диск.
//
// minIndex — первый номер, который выдаётся кому-либо, кроме режимов роутера.
// Номера 0 и 1 держатся за ними, и это наше решение (#891): режим роутера в
// любой момент работает ОДИН, и встречные потоки перебора расходятся — он идёт
// снизу, остальные сверху, — поэтому общий перебор снизу голодил бы именно его.
// Два номера, а не один: смена режима недолго держит старый и новый индекс
// одновременно.
//
// Потолок у режима роутера тот же, что у всех: прежнее окно 0..9 было нашим
// делением, а не фактом прошивки, и снято вместе с остальными собственными
// окнами.
//
// Резерв — правило ВЫДАЧИ, а не владения: уже существующие записи на 0/1
// (легаси awg0/awg1, прокси-инстанс старой установки) свои номера сохраняют,
// занятость их защищает.
//
// Неэкспортируем намеренно: у границы ровно один потребитель — перебор в этом
// же пакете, и экспорт был бы приглашением решить «с какого номера начинать»
// ещё раз, на стороне. Копия правила обхода — это и есть #891. Экспорт жил
// только потому, что константа лежала в чужом пакете.
const minIndex = 2

// Ceiling — максимальный номер OpkgTun, который поднимет прошивка.
// Факт железа, не наше решение: на mips/mipsel запрос OpkgTun17 отвергается
// («index 17 is too large for "OpkgTun" interface», стенд 5.1.3, замерено
// 18.08 и перепроверено 25.08.2026), рабочий максимум там 16; на arm/arm64
// рабочий максимум 49 — замер владельца на железе. Поднимать границу mips
// нельзя без нового замера: это не наша политика, а ответ прошивки.
//
// Аргументом, а не runtime.GOARCH внутри, — чтобы тест не зависел от машины,
// на которой его запустили.
func Ceiling(goarch string) int {
	switch goarch {
	case "mips", "mipsle", "mips64", "mips64le":
		return 16
	default:
		return 49
	}
}

// CeilingForHost — потолок ЭТОЙ сборки. Единственное место, где карта
// спрашивается про runtime.GOARCH.
//
// Копий этого выражения быть не должно, и причина не стилистическая: потолок
// спрашивают ДВОЕ — проводка, строящая пул, и пол диапазона NativeWG, который
// обязан лежать выше него (storage.nwgFloor, F317). Разойдись они, диапазоны
// пересеклись бы, а страж непересечения, сверяющий карту саму с собой, этого
// бы не заметил.
func CeilingForHost() int { return Ceiling(runtime.GOARCH) }
