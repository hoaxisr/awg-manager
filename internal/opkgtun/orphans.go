package opkgtun

import (
	"context"
	"fmt"
)

// Orphan — номер, за которым стоит ТОЛЬКО след и ни одной записи владельца.
//
// След — это живое устройство в ядре и/или запись NDMS: оба держателя
// безключевые (см. AnonHolder). Запись владельца — туннель, инстанс прокси
// или режим роутера — ключ имеет всегда. Отсюда предикат: номер осиротел,
// если КАЖДЫЙ его держатель анонимен.
type Orphan struct {
	Index int
}

// Orphans — номера, потерявшие владельца.
//
// Читает те же источники, что и выдача, и тем же составом: спрашивать
// занятость своим набором — это ровно #891, с той разницей, что здесь ошибка
// не уводит чужой номер, а называет чужой интерфейс сиротой.
//
// Семафор pick НЕ берётся: это чтение, оно ничего не выбирает и никого не
// должно ждать. Но незакрытые резервации вычитаются — номер, выданный прямо
// сейчас, ещё не дошёл до записи владельца и выглядел бы осиротевшим, а
// показать его пользователю значит предложить снести интерфейс, который в эту
// секунду создают.
//
// Ошибка любого источника отказывает всему ответу, а не отдаёт неполный
// список: недосчёт держателей здесь — это ложная сирота, то есть предложение
// удалить живое.
func (p *Pool) Orphans(ctx context.Context) ([]Orphan, error) {
	return p.orphans(ctx)
}

// OrphansExclusive — то же, но под семафором выбора.
//
// Разница несущая, и она про ЦЕНУ ОШИБКИ. Лишняя строка в показе — досадно и
// живёт до следующего опроса. Лишняя строка под кнопкой «удалить» — снос
// интерфейса, который в эту секунду создают. Поэтому показ читает без замка
// (иначе каждый опрос списка вставал бы в очередь с выдачей номеров — а он
// идёт раз в несколько секунд), а перепроверка перед сносом берёт pick и
// закрывает окно целиком: пока он у нас, ни одна резервация не откроется и не
// закроется.
//
// Отмена ждётся по контексту: «передумали» и «пул занят» — разные новости.
func (p *Pool) OrphansExclusive(ctx context.Context) ([]Orphan, error) {
	select {
	case p.pick <- struct{}{}:
	case <-ctx.Done():
		return nil, ctx.Err()
	}
	defer func() { <-p.pick }()
	return p.orphans(ctx)
}

func (p *Pool) orphans(ctx context.Context) ([]Orphan, error) {
	before := p.earlySnapshot()
	parts := make([]Taken, 0, len(p.src))
	for _, s := range p.src {
		got, err := s.Read(ctx)
		if err != nil {
			return nil, fmt.Errorf("занятость OpkgTun (%s): %w", s.Name, err)
		}
		parts = append(parts, got)
	}
	occ, _ := mergeAll(parts)
	// Снимок резерваций берётся ДВАЖДЫ и объединяется: взятый до чтения не
	// увидит резервацию, ОТКРЫТУЮ во время чтения, а взятый после — ЗАКРЫТУЮ во
	// время чтения. Reserve обходится одним ранним срезом потому, что держит
	// pick, и при нём reserved умеет только сжиматься (pool.go).
	//
	// Двух снимков всё равно НЕ ХВАТАЕТ, и врать об этом нельзя: резервация,
	// успевшая открыться и закрыться ЦЕЛИКОМ внутри чтения источников, не видна
	// ни одному из них, а запись её владельца легла на диск позже, чем мы
	// прочли его источник, — значит нет её и в занятости. Окно узкое, но не
	// нулевое, и закрывается оно единственным способом — семафором выбора
	// (OrphansExclusive), которым и ходит перепроверка перед сносом.
	//
	// Цена оставшегося окна односторонняя: номер, побывавший в резервации, один
	// раз не покажется сиротой.
	reserved := p.earlySnapshot()

	out := []Orphan{}
	for n := 0; n <= p.ceiling; n++ {
		hs := occ[n]
		if len(hs) == 0 {
			continue
		}
		if _, held := reserved[n]; held {
			continue
		}
		if _, held := before[n]; held {
			continue
		}
		owned := false
		for _, h := range hs {
			if !h.anonymous() {
				owned = true
				break
			}
		}
		if owned {
			continue
		}
		out = append(out, Orphan{Index: n})
	}
	return out, nil
}
