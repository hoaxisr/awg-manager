/**
 * mergedPrefix — сколько системных строк режимного слота идёт в трассе перед
 * первым правилом со страницы правил.
 *
 * Инспектор ходит по ОБЪЕДИНЁННОМУ конфигу режима (#488): режимный слот
 * сливается первым, поэтому сверху лежат его системные правила (sniff,
 * hijack-dns, ip_is_private, route-options), которых нет ни в ListRules, ни на
 * странице правил. Разница длин и есть смещение нумерации.
 *
 * @param walked   сколько правил прошёл инспектор (result.matches.length)
 * @param listed   сколько правил показывает страница (rules.length)
 *
 * Два края, ради которых функция вообще существует:
 *   - холодный стор (listed === 0) — длину списка ещё не знаем, и разница
 *     объявила бы ВСЕ пройденные правила системными; в этом случае молчим;
 *   - list опередил трассу (правило добавлено после прогона) — разница
 *     отрицательная, наружу отдаём 0, а не минус.
 */
export function mergedPrefix(walked: number, listed: number): number {
	return listed > 0 ? Math.max(0, walked - listed) : 0;
}
